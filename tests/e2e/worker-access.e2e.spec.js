import { expect, test } from '@playwright/test'

const admin = { email: 'admin.e2e@example.test', password: 'E2e-Admin-Password-2026!' }
const initial = 'Worker-Onboard-2026!'
const changed = 'Worker-Changed-2026!'
const recovered = 'Worker-Recovered-2026!'

async function signInEmail(page) {
  await page.goto('/')
  await page.getByLabel('Correo').fill(admin.email)
  await page.getByLabel('Contraseña').fill(admin.password)
  await page.getByRole('button', { name: 'Iniciar sesion' }).click()
  const transientError = page.getByText('Failed to fetch')
  for (let attempt = 0; attempt < 5 && await transientError.isVisible({ timeout: 200 }).catch(() => false); attempt += 1) { await page.waitForTimeout(1000); await page.getByRole('button', { name: 'Iniciar sesion' }).click() }
  await expect(page.getByRole('button', { name: 'Trabajadores' })).toBeVisible()
}

test('alta, login DNI/NIE, cambio de contraseña y baja con sesión previa', async ({ browser }) => {
  const adminContext = await browser.newContext(); const adminPage = await adminContext.newPage()
  await signInEmail(adminPage)
  await adminPage.getByRole('button', { name: 'Trabajadores' }).click()
  await adminPage.getByRole('button', { name: 'Nuevo trabajador' }).click()
  await adminPage.locator('#worker-employeeCode').fill('E2E-ACCESS-001')
  await adminPage.locator('#worker-firstName').fill('Acceso')
  await adminPage.locator('#worker-lastName').fill('Navegador')
  await adminPage.locator('#worker-document').fill('00000008P')
  await adminPage.locator('#worker-phone').fill('600999999')
  await adminPage.locator('#worker-status').selectOption('active')
  await adminPage.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(adminPage.getByRole('status')).toContainText('Ficha guardada correctamente.')
  const accessRow = adminPage.locator('.worker-desktop-table tr').filter({ hasText: 'Acceso Navegador' })
  await accessRow.getByRole('button', { name: 'Habilitar acceso' }).click()
  const accessDialog = adminPage.getByRole('dialog')
  await accessDialog.locator('#worker-access-password').fill(initial)
  await accessDialog.getByRole('button', { name: 'Habilitar acceso', exact: true }).click()
  await expect(adminPage.getByRole('status')).toContainText('Acceso habilitado')
  await adminPage.getByRole('button', { name: 'Cerrar sesión' }).click()
  await expect(adminPage.getByRole('heading', { name: 'Iniciar sesion' })).toBeVisible()

  await adminPage.getByRole('button', { name: 'Acceder como trabajador con DNI/NIE' }).click()
  await adminPage.getByLabel('DNI/NIE').fill('00000008P')
  await adminPage.getByLabel('Contraseña').fill(initial)
  await adminPage.getByRole('button', { name: 'Iniciar sesion' }).click()
  await expect(adminPage.getByRole('heading', { name: 'Fichaje' })).toBeVisible()
  await adminPage.getByRole('button', { name: 'Registrar entrada' }).click()
  await expect(adminPage.getByRole('button', { name: 'Registrar salida' })).toBeVisible()
  await adminPage.getByRole('button', { name: 'Perfil' }).click()
  await adminPage.getByLabel('Nueva contraseña').fill(changed)
  await adminPage.getByRole('button', { name: 'Cambiar contraseña' }).click()
  await expect(adminPage.getByText('Contraseña actualizada correctamente.')).toBeVisible()
  await adminPage.getByRole('button', { name: 'Cerrar sesión' }).click()
  await adminPage.getByRole('button', { name: 'Acceder como trabajador con DNI/NIE' }).click()
  await adminPage.getByLabel('DNI/NIE').fill('00000008P'); await adminPage.getByLabel('Contraseña').fill(initial)
  await adminPage.getByRole('button', { name: 'Iniciar sesion' }).click()
  await expect(adminPage.getByText('No se pudo iniciar sesión con esas credenciales.')).toBeVisible()
  await adminPage.getByLabel('Contraseña').fill(changed); await adminPage.getByRole('button', { name: 'Iniciar sesion' }).click()
  await expect(adminPage.getByRole('heading', { name: 'Fichaje' })).toBeVisible()

  const admin2 = await browser.newPage(); await signInEmail(admin2)
  await admin2.getByRole('button', { name: 'Trabajadores' }).click()
  const adminRow = admin2.locator('.worker-desktop-table tr').filter({ hasText: 'Acceso Navegador' })
  await adminRow.getByRole('button', { name: 'Detalle de Acceso Navegador' }).click()
  await adminRow.getByRole('button', { name: 'Restablecer acceso' }).click()
  const resetDialog = admin2.getByRole('dialog')
  await resetDialog.locator('#worker-reset-password').fill(recovered)
  await resetDialog.getByRole('button', { name: 'Restablecer acceso', exact: true }).click()
  await expect(admin2.getByRole('status')).toContainText('Acceso restablecido')
  await adminPage.getByRole('button', { name: 'Cerrar sesión' }).click()
  await adminPage.getByRole('button', { name: 'Acceder como trabajador con DNI/NIE' }).click()
  await adminPage.getByLabel('DNI/NIE').fill('00000008P'); await adminPage.getByLabel('Contraseña').fill(changed)
  await adminPage.getByRole('button', { name: 'Iniciar sesion' }).click()
  await expect(adminPage.getByText('No se pudo iniciar sesión con esas credenciales.')).toBeVisible()
  await adminPage.getByLabel('Contraseña').fill(recovered); await adminPage.getByRole('button', { name: 'Iniciar sesion' }).click()
  await expect(adminPage.getByRole('heading', { name: 'Fichaje' })).toBeVisible()
  await adminPage.getByRole('button', { name: 'Actualizar jornada' }).click()
  await admin2.getByRole('button', { name: 'Archivar a Acceso Navegador' }).click()
  await admin2.locator('#archive-reason').fill('Desactivación E2E')
  await admin2.getByRole('button', { name: 'Confirmar archivo' }).click()
  await expect(admin2.getByRole('status')).toContainText('Ficha archivada')
  await adminPage.getByRole('button', { name: 'Registrar salida' }).click()
  await expect(adminPage.getByRole('alert')).toContainText('No tienes una ficha de trabajador activa vinculada.')
  await admin2.close(); await adminContext.close()
})
